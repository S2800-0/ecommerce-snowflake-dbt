-- Task 1: set up Snowflake.
-- Run in Snowsight with Run All. Replace <PUBLIC_KEY> with the public key printed by
-- scripts/new_keypair.sh (one line, no BEGIN or END lines).

-- A dedicated role and service user for dbt, with key pair login
USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS DBT_ROLE;
CREATE USER IF NOT EXISTS DBT_USER
  TYPE = SERVICE
  DEFAULT_ROLE = DBT_ROLE
  RSA_PUBLIC_KEY = '<PUBLIC_KEY>';
GRANT ROLE DBT_ROLE TO USER DBT_USER;

-- A small warehouse that suspends after 60 seconds
USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS ECOMMERCE_WH
  WAREHOUSE_SIZE = XSMALL
  WAREHOUSE_TYPE = STANDARD
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;
GRANT USAGE ON WAREHOUSE ECOMMERCE_WH TO ROLE DBT_ROLE;

-- The database and its three schemas
CREATE DATABASE IF NOT EXISTS ECOMMERCE_DB;
CREATE SCHEMA IF NOT EXISTS ECOMMERCE_DB.RAW;
CREATE SCHEMA IF NOT EXISTS ECOMMERCE_DB.STAGING;
CREATE SCHEMA IF NOT EXISTS ECOMMERCE_DB.MARTS;

-- dbt needs to own what it builds. Give the database and every schema in it to DBT_ROLE.
GRANT OWNERSHIP ON ALL SCHEMAS IN DATABASE ECOMMERCE_DB TO ROLE DBT_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON DATABASE ECOMMERCE_DB TO ROLE DBT_ROLE COPY CURRENT GRANTS;

USE ROLE ACCOUNTADMIN;
ALTER USER DBT_USER SET DEFAULT_WAREHOUSE = ECOMMERCE_WH;

-- Checks
SHOW SCHEMAS IN DATABASE ECOMMERCE_DB;
SHOW USERS LIKE 'DBT_USER';
SHOW WAREHOUSES LIKE 'ECOMMERCE_WH';
